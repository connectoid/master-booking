"""Тексты и форматирование дат для сообщений бота."""
from __future__ import annotations

import datetime as dt
from zoneinfo import ZoneInfo

WEEKDAYS = ["пн", "вт", "ср", "чт", "пт", "сб", "вс"]
MONTHS = ["янв", "фев", "мар", "апр", "мая", "июн", "июл", "авг", "сен", "окт", "ноя", "дек"]

TIMEZONES: list[tuple[str, str]] = [
    ("Калининград (МСК−1)", "Europe/Kaliningrad"),
    ("Москва (МСК)", "Europe/Moscow"),
    ("Самара (МСК+1)", "Europe/Samara"),
    ("Екатеринбург (МСК+2)", "Asia/Yekaterinburg"),
    ("Омск (МСК+3)", "Asia/Omsk"),
    ("Новосибирск, Красноярск (МСК+4)", "Asia/Krasnoyarsk"),
    ("Иркутск (МСК+5)", "Asia/Irkutsk"),
    ("Якутск (МСК+6)", "Asia/Yakutsk"),
    ("Владивосток (МСК+7)", "Asia/Vladivostok"),
    ("Магадан (МСК+8)", "Asia/Magadan"),
    ("Камчатка, Чукотка (МСК+9)", "Asia/Kamchatka"),
]
TIMEZONE_IDS = {tz for _, tz in TIMEZONES}


def fmt_day(d: dt.date) -> str:
    """«ср, 15 окт»"""
    return f"{WEEKDAYS[d.weekday()]}, {d.day} {MONTHS[d.month - 1]}"


def fmt_when(starts_at: dt.datetime, tz: ZoneInfo) -> str:
    """«ср, 15 окт в 14:00»"""
    local = starts_at.astimezone(tz)
    return f"{fmt_day(local.date())} в {local:%H:%M}"


def fmt_price(price: int | None) -> str:
    return f"{price:,} ₽".replace(",", " ") if price is not None else "цена по договорённости"


