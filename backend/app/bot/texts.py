LEAD_OPTIONS = [(0, "сразу"), (60, "1 ч"), (120, "2 ч"), (180, "3 ч"), (360, "6 ч"),
                (720, "12 ч"), (1440, "сутки")]
HORIZON_OPTIONS = [7, 14, 30, 60, 90]
STEP_OPTIONS = [10, 15, 20, 30, 60]     # шаг сетки времени записи, мин
BUFFER_OPTIONS = [0, 5, 10, 15, 30]     # пауза между клиентами, мин


def fmt_lead(minutes: int) -> str:
    for value, title in LEAD_OPTIONS:
        if value == minutes:
            return "можно записаться в любой момент" if value == 0 else f"не позже чем за {title}"
    return f"не позже чем за {minutes // 60} ч {minutes % 60} мин".replace(" 0 мин", "")
